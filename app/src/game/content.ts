export function characterById(id: CharacterId): CharacterDef {
  return CHARACTERS.find((c) => c.id === id) ?? CHARACTERS[0];
}

export function levelsFor(id: CharacterId): LevelDef[] {
  return LEVELS.filter((level) => level.char === id);
}
